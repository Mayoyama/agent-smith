"""Pydantic models for the LLM provider configuration."""

from pydantic import BaseModel, Field, model_validator, field_validator


class LLMProvider(BaseModel):
    """One provider entry from the models config file.

    Attributes:
        name: Provider name, e.g. "groq".
        base_url: Base URL of the provider's OpenAI-compatible API, starting
            with http:// or https://.
        key_prefix: Prefix of the environment variables that hold the
            provider's API keys, e.g. GROQ_API_KEY.
    """

    name: str = Field(min_length=1)
    base_url: str = Field(min_length=5)
    key_prefix: str = Field(min_length=1)

    @model_validator(mode='after')
    def validate_url(self) -> "LLMProvider":
        """Check that base_url starts with http:// or https://.

        Returns:
            The validated provider.

        Raises:
            ValueError: If base_url starts with neither.
        """

        if (not self.base_url.startswith("http://")
                and not self.base_url.startswith("https://")):
            raise ValueError("base_url must start with http:// or https://")

        return self


class LLMProviderList(BaseModel):
    """All provider entries from the models config file.

    Attributes:
        providers: The configured providers, at least one.
    """

    providers: list[LLMProvider] = Field(min_length=1)


class LLMModelData(BaseModel):
    """Everything needed to send requests to one model.

    Attributes:
        base_url: Base URL of the provider's OpenAI-compatible API, starting
            with http:// or https://.
        model_name: Model to request, e.g. "openai/gpt-oss-20b".
        api_keys: The provider's API keys, tried in this order; at least one.
    """

    base_url: str = Field(min_length=5)
    model_name: str = Field(min_length=1)
    api_keys: list[str] = Field(min_length=1)

    @field_validator("base_url")
    @classmethod
    def validate_url(cls, value: str) -> str:
        """Check that base_url starts with http:// or https://.

        Args:
            value: The base_url to check.

        Returns:
            The unchanged base_url.

        Raises:
            ValueError: If base_url starts with neither.
        """

        if (not value.startswith("http://")
                and not value.startswith("https://")):
            raise ValueError("base_url must start with http:// or https://")

        return value


class RequestData(BaseModel):
    """Result of one request to the LLM API.

    Attributes:
        text: The reply text, or an empty string if the request failed.
        input_tokens: Tokens sent to the model (prompt tokens), 0 if the
            request failed.
        output_tokens: Tokens generated by the model (completion tokens), 0 if
            the request failed.
        response_time_in_ms: Wall-clock time of the HTTP request in
            milliseconds.
        reply_code: HTTP status code of the response.
        retry_after: Seconds the provider asked to wait before retrying, or
            None if it gave no time or the request succeeded.
    """

    text: str
    input_tokens: int = Field(ge=0)
    output_tokens: int = Field(ge=0)
    response_time_in_ms: float = Field(ge=0.0)
    reply_code: int = Field(ge=0)
    retry_after: float | None = None
